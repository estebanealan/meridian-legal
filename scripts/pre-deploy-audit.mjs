// scripts/pre-deploy-audit.mjs
import fs from 'node:fs'
import path from 'node:path'
import { execSync } from 'node:child_process'

console.log("🔍 VRC-ELITE Pre-Deploy Audit v2026.5...")
let failed = false
const IGNORE = ['node_modules', '.next', '.git', 'dist', 'build', '.turbo']
const IGNORE_FILES = ['package-lock.json', 'pnpm-lock.yaml', 'pre-deploy-audit.mjs']

const FORBIDDEN_FILES = [
  /\.log(\..*)?$/, /build_.*\.txt/, /audit.*\.txt/, /temp_.*/, /\.code-workspace/, /\.idea/,
  /VRC-ELITE-.*\.md/, /GEMINI\.md/, /\.map$/, /inject_.*\.js/, /patch_.*\.js/,
  /\.swp$/, /\.bak$/, /\.orig$/, /diff\.patch/, /railway_login.*/, /skills-lock\.json/
]

const AI_PATTERNS = [
  "Generated by", "Copilot", "ChatGPT", "Claude", "AI-generated", "AI generated",
  "Gemini", "GPT-4", "created by AI", "auto-generated", "LLM",
  "Cursor", "Windsurf", "Codeium", "v0", "Bolt", "Anthropic", "OpenAI", "DeepSeek",
  "this code was", "written by", "assisted by",
  "TODO: implement", "FIXME: add", "FIXME: complete", "TODO: finish",
  "Lorem ipsum", "placeholder text", "test content here", "example.com", "foo@bar"
]

const SECRET_PATTERNS = [
  "sk_live_", "sk_test_", "pk_live_", "AKIA", "ghp_", "glpat-", "xox[bpsa]-",
  "-----BEGIN.*KEY-----", "password.*=['\"]", "secret.*=['\"]",
  "BETTER_AUTH_SECRET", "MEDUSA_WEBHOOK_SECRET", "whsec_", "rk_live_", "rk_test_"
]

const OBVIOUS_COMMENTS = /\/\/ (loop|iterate|get|set|return|check|handle|create|delete|update|render) /i

let hasPrefersReducedMotion = false, hasJsonLd = false
const largeImages = []

function scan(dir) {
  for (const file of fs.readdirSync(dir)) {
    const full = path.join(dir, file)
    const stat = fs.statSync(full)
    if (stat.isDirectory()) { if (!IGNORE.includes(file)) scan(full); continue }

    if (FORBIDDEN_FILES.some(r => r.test(file))) { console.error(`❌ Basura: ${full}`); failed = true; continue }
    if (IGNORE_FILES.includes(file)) continue
    if (/^\.env(\.local|\.production)?$/.test(file)) { console.error(`❌ Env real: ${full}`); failed = true }
    if (/\.(png|jpe?g)$/i.test(file) && stat.size > 500 * 1024) largeImages.push(full)

    if (/\.(ts|tsx|js|jsx|json|md|css|html|astro)$/.test(file)) {
      const content = fs.readFileSync(full, 'utf8')
      AI_PATTERNS.forEach(p => { if (content.includes(p)) { console.error(`❌ AI rastro en ${full}: "${p}"`); failed = true } })
      SECRET_PATTERNS.forEach(p => { if (new RegExp(p).test(content)) { console.error(`🚨 SECRETO en ${full}: "${p}"`); failed = true } })
      if (content.includes('console.log') && !content.includes('eslint-disable')) console.warn(`⚠️ console.log: ${full}`)
      if (OBVIOUS_COMMENTS.test(content)) console.warn(`⚠️ Comentario QUÉ vs POR QUÉ: ${full}`)
      if (content.includes('prefers-reduced-motion')) hasPrefersReducedMotion = true
      if (content.includes('application/ld+json')) hasJsonLd = true
    }
  }
}

scan('.')

try {
  const log = execSync('git log --oneline -20', { encoding: 'utf8' })
  if (/(update files|add feature|fix stuff|initial commit|wip|test|asdf|misc)/i.test(log))
    console.warn("⚠️ Commits genéricos. Conventional Commits.")
} catch {}

try {
  const gi = fs.readFileSync('.gitignore', 'utf8')
  ;['*.log', '.env', 'src/generated/', '*.map'].forEach(p => { if (!gi.includes(p)) console.warn(`⚠️ Falta .gitignore: ${p}`) })
} catch { console.error("❌ Falta .gitignore"); failed = true }

if (largeImages.length) { console.warn("⚠️ Imágenes > 500KB:"); largeImages.forEach(i => console.warn(`   - ${i}`)) }
if (!hasPrefersReducedMotion) { console.error("❌ prefers-reduced-motion NO implementado."); failed = true }
if (!hasJsonLd) console.warn("⚠️ No JSON-LD encontrado.")

;['src/app/robots.ts', 'src/app/sitemap.ts', 'public/og-default.jpg'].forEach(f => { if (!fs.existsSync(f)) console.warn(`⚠️ Falta SEO: ${f}`) })

if (failed) { console.log("\n╔══════════════════════════════════════╗\n║  ❌ PRE-DEPLOY BLOQUEADO             ║\n╚══════════════════════════════════════╝"); process.exit(1) }
else console.log("✅ Limpio. Validando framework...")
